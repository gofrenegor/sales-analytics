const STATUS_NAMES = new Map(STATUSES);

function statusDescription(code) {
  return STATUS_NAMES.get(String(code || "").trim().toUpperCase()) || "";
}

function renderStatuses() {
  const host = document.getElementById("info-status-list");
  if (!host || typeof el !== "function") return;
  const query = (document.getElementById("status-search")?.value || "").trim().toLowerCase();
  const rows = STATUSES.filter(([code, name]) => {
    if (!query) return true;
    return code.toLowerCase().includes(query) || name.toLowerCase().includes(query);
  });
  if (!rows.length) {
    host.replaceChildren(el("p", { class: "st-empty" }, "нет такого статуса"));
    return;
  }
  host.replaceChildren(...rows.map(([code, name]) => el(
    "div",
    { class: "st-row" },
    el("b", { class: "st-code" }, code),
    el("span", null, name),
  )));
}

function wireStatusSearch() {
  const input = document.getElementById("status-search");
  if (!input || input.dataset.wired) return;
  input.dataset.wired = "1";
  input.addEventListener("input", () => renderStatuses());
}

function renderInfoCatalog() {
  const host = document.getElementById("info-lr-list");
  if (!host || typeof el !== "function") return;
  host.replaceChildren(...LOST_REASONS.map(renderLost));
  wireStatusSearch();
  renderStatuses();
}

