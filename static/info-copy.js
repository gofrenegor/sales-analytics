function withLrNums(text) {
  const nodes = [];
  const re = /\d{1,2}/g;
  let last = 0;
  let match;
  while ((match = re.exec(text))) {
    const n = match[0];
    const i = match.index;
    const prev = i > 0 ? text[i - 1] : "";
    const next = text[i + n.length] || "";
    if (/\d/.test(prev) || /\d/.test(next) || prev === "." || next === "." || !LR_NUMS.has(n)) continue;
    if (i > last) nodes.push(document.createTextNode(text.slice(last, i)));
    nodes.push(el("b", { class: "lr-num" }, n));
    last = i + n.length;
  }
  if (last < text.length) nodes.push(document.createTextNode(text.slice(last)));
  if (!nodes.length) nodes.push(document.createTextNode(text));
  return nodes;
}

function renderCopySection(section) {
  const nodes = [el("h3", null, section.h)];
  for (const para of section.p || []) nodes.push(el("p", null, ...withLrNums(para)));
  if (section.items) {
    nodes.push(el("ul", null, ...section.items.map((item) => el("li", null, ...withLrNums(item)))));
  }
  for (const para of section.tail || []) nodes.push(el("p", null, ...withLrNums(para)));
  return el("section", null, ...nodes);
}

function renderLost(item) {
  const id = el(
    "span",
    { class: "lr-id" },
    "Lostreason ",
    el("b", { class: "lr-num" }, `№${item.n}`),
  );
  if (item.mark) id.append(el("span", { class: "lr-mark" }, item.mark));
  const body = [];
  if (item.alert) body.push(el("p", { class: "lr-alert" }, ...withLrNums(item.alert)));
  for (const section of item.sections) body.push(renderCopySection(section));
  return el(
    "details",
    { class: "lr" },
    el(
      "summary",
      null,
      el("span", { class: "lr-head" }, id, el("span", { class: "lr-title" }, item.title)),
      el("span", { class: "lr-chev", "aria-hidden": "true" }),
    ),
    el("div", { class: "lr-body" }, ...body),
  );
}

function renderInfoCatalog() {
  const host = document.getElementById("info-lr-list");
  if (!host || typeof el !== "function") return;
  host.replaceChildren(...LOST_REASONS.map(renderLost));
}

